# Generates the Thai Aluwork (ALUWORK.pdf, "aluframe Light") import: supabase/datafix/2026-11-04-import-aluwork.sql.
# Weights: catalogue prints kg per bar as ranges for anodize and powder coat; same rule the owner chose for Fuji market
# (2026-11-04, choice 1): midpoint of the POWDER COAT range / bar length (anodize if no powder value).
# Prices = SMS shop rates: 170 THB/kg, every wood-grain shade 350 (owner 2026-11-04).
import json, uuid, os, re
from PIL import Image, ImageDraw, ImageFont
ROOT='/Users/plfx/code/FacadeXPM/facadex-app'
X=ROOT+'/DOC/ALUMNIUM CATALOG/_extracted/aluwork-sections'
OUT=os.path.dirname(os.path.abspath(__file__))
T='1b9affc4-2136-4ed1-b168-a36e6624e743'
d=json.load(open(ROOT+'/docs/catalogs/aluwork/aluwork-2024.json'))
man={m['die']:m for m in json.load(open(X+'/manifest.json')) if m.get('file')}
ns=uuid.UUID('6f1c2a90-0000-4000-8000-0000a1a0a0a1')
uid=lambda *k: str(uuid.uuid5(ns,'|'.join(map(str,k))))
SER={0:('aluframe Light','บานเลื่อน ประตู-หน้าต่าง (เฟรม 95 / 71.5 / 101.6)',['บานเลื่อนสวน 2 บาน','บานเลื่อน 2 ตาย 2','บานติดตาย']),
     1:('aluframe Light','บานกระทุ้ง / บานเปิด (ยูเนี่ยน + มาตรฐาน)',['บานกระทุ้ง','บานเปิด','บานติดตาย']),
     2:('aluframe Light','บานสวิง - ช่องแสง (กล่อง 4")',['บานสวิง','บานสวิงเดี่ยว','บานสวิงคู่','บานติดตาย']),
     3:('aluframe Light','ช่องแสง 3"',['บานติดตาย']),
     4:('aluframe Light','ประตูบานเปิด',['บานเปิด']),
     5:('STANDARD','กล่อง (ระแนง)',[]),
     6:('STANDARD','อื่นๆ (ตัวยู ตัวแซด ลูกฟูก)',[])}
FIN=[('อบขาว',170),('อบดำ',170),('อบสีเทา / แชมเปญ',170),('สีชุบ (อโนไดซ์)',170),
     ('ลายไม้ Tassie Oak',350),('ลายไม้ French Oak',350),('ลายไม้ Teak Brown',350),('ลายไม้ Teak Dark Brown',350)]
prov=uid('provider')
q=lambda s: "'"+str(s).replace("'","''")+"'" if s is not None else 'NULL'
num=lambda v: 'NULL' if v in (None,'') else repr(round(float(v),4))
def weight(p):
    n=p.get('note') or ''
    bar=re.search(r'per (\d+(?:\.\d+)?) m bar', n); L=float(bar.group(1)) if bar else float(p.get('std_length_m') or 6.4)
    for tag in ('powder coat','anodize'):
        m=re.search(tag+r' (\d+(?:\.\d+)?)(?:-(\d+(?:\.\d+)?))? kg', n)
        if m: a=float(m.group(1)); b=float(m.group(2) or a); return (a+b)/2/L, f'{tag} {m.group(0)[len(tag)+1:]} / {L:g} m'
    return float(p['kg_per_m']), 'kg/m as extracted'
walls=sorted({p['wall_mm'] for i in (5,6) for p in d['series'][i]['profiles'] if p.get('wall_mm')})
FAM=[('aluframe Light',1,None),('STANDARD',0,'{'+','.join('%g'%w if '.' in '%g'%w else '%g.0'%w for w in walls)+'}')]
profiles=[]; links=[]
for i,(fam,sname,types) in SER.items():
    sid=uid('series',sname)
    for p in d['series'][i]['profiles']:
        key=p['die_no']
        kgm,basis=weight(p)
        bad=('cannot weigh' in (p.get('note') or '')) or ('untrustworthy' in (p.get('note') or ''))
        pid=uid('profile',key)
        if pid not in {x['id'] for x in profiles}:
            profiles.append(dict(p, id=pid, code=re.sub(r'-p\d+n\d+$','',key), key=key, kgm=kgm, basis=basis, active=not bad))
        links.append((sid,pid,p.get('role_family') or 'อื่นๆ'))
links=list(dict.fromkeys(links))
font=ImageFont.truetype('/System/Library/Fonts/Helvetica.ttc',30)
os.makedirs(OUT+'/img',exist_ok=True); imgs=[]
def label(t):
    if t in (None,''): return 't = ?'
    v=float(t); return 't = '+(f'{v:.1f}' if round(v,1)==v else f'{v:g}')+' mm'
for p in profiles:
    m=man.get(p['key'])
    if not m: p['image_path']=None; continue
    im=Image.open(X+'/'+m['file']).convert('RGB'); w,h=im.size; band=48
    o=Image.new('RGB',(w,h+band),'white'); o.paste(im,(0,0)); dr=ImageDraw.Draw(o); lb=label(p.get('wall_mm'))
    dr.text(((w-dr.textlength(lb,font=font))/2,h+6),lb,fill='black',font=font)
    fn=p['id']+'.png'; o.save(OUT+'/img/'+fn,optimize=True)
    p['image_path']=f'{T}/profiles/{p["id"]}.png'; imgs.append({'id':p['id'],'file':fn,'code':p['key']})
json.dump(imgs,open(OUT+'/list.json','w'))
L=["-- Owner 2026-11-04: import Thai Aluwork (ALUWORK.pdf, aluframe Light) as an extruder, prices like SMS (wood grain 350 every shade).",
"-- Data docs/catalogs/aluwork/aluwork-2024.json; kg/m = midpoint of the powder-coat kg-per-bar range / bar length (Fuji-market rule).",
"-- Codes printed twice by the catalogue keep the printed code as DIE NO.; the two คิ้วลอยเทเล็ก rows whose weights were copied from",
"-- ขวางล่าง are imported INACTIVE (weight not trustworthy). Generated by 2026-11-04-import-aluwork.gen.py; refuses to run twice.",
"BEGIN;",
f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM alu_providers WHERE tenant_id = {q(T)} AND (id = {q(prov)} OR short_name = 'AW')) THEN RAISE EXCEPTION 'Aluwork already imported'; END IF; END $$;",
f"INSERT INTO alu_providers (id, tenant_id, name, short_name, price_basis, active) VALUES ({q(prov)}, {q(T)}, 'Thai Aluwork (aluframe)', 'AW', 'per_kg', true);"]
for name,price in FIN:
    fid=uid('finish',name)
    L.append(f"INSERT INTO alu_finishes (id, tenant_id, provider_id, name, active) VALUES ({q(fid)}, {q(T)}, {q(prov)}, {q(name)}, true);")
    L.append(f"INSERT INTO alu_kg_prices (tenant_id, provider_id, finish_id, price_per_kg, effective_from, source) VALUES ({q(T)}, {q(prov)}, {q(fid)}, {price}, '2026-01-01', 'same as SMS shop rate (owner 2026-11-04)');")
for f,o,th in FAM:
    L.append(f"INSERT INTO alu_series_families (id, tenant_id, provider_id, name, thickness_options, sort_order, active) VALUES ({q(uid('family',f))}, {q(T)}, {q(prov)}, {q(f)}, {q(th) if th else 'NULL'}, {o}, true);")
for i,(fam,sname,types) in SER.items():
    sid=uid('series',sname)
    L.append(f"INSERT INTO alu_series (id, tenant_id, provider_id, name, is_base, active, series_family_id) VALUES ({q(sid)}, {q(T)}, {q(prov)}, {q(sname)}, false, true, {q(uid('family',fam))});")
    for t in types:
        L.append(f"INSERT INTO alu_series_types (tenant_id, series_id, type_id) SELECT {q(T)}, {q(sid)}, id FROM door_window_types WHERE tenant_id = {q(T)} AND name = {q(t)};")
for p in profiles:
    L.append(f"-- {p['key']}: {p['basis']}")
    L.append("INSERT INTO alu_profiles (id, tenant_id, provider_id, name, drawing_no, family, thickness_mm, linear_weight_kg_per_m, default_length_m, width_mm, depth_mm, active, image_path) VALUES "
             f"({q(p['id'])}, {q(T)}, {q(prov)}, {q(p['name'])}, {q(p['code'])}, {q(p.get('role_family') or 'อื่นๆ')}, {num(p.get('wall_mm'))}, {num(p['kgm'])}, {num(p.get('std_length_m') or 6.4)}, {num(p.get('width_mm'))}, {num(p.get('depth_mm'))}, {'true' if p['active'] else 'false'}, {q(p['image_path'])});")
for sid,pid,fam in links:
    L.append(f"INSERT INTO alu_series_profiles (tenant_id, series_id, profile_id, family) VALUES ({q(T)}, {q(sid)}, {q(pid)}, {q(fam)});")
nt=sum(len(v[2]) for v in SER.values())
L.append(f"""DO $$ DECLARE a int; b int; c int; d int; e int; f int; BEGIN
  SELECT count(*) INTO a FROM alu_series WHERE provider_id = {q(prov)};
  SELECT count(*) INTO b FROM alu_profiles WHERE provider_id = {q(prov)};
  SELECT count(*) INTO c FROM alu_series_profiles sp JOIN alu_series s ON s.id = sp.series_id WHERE s.provider_id = {q(prov)};
  SELECT count(*) INTO d FROM alu_series_types st JOIN alu_series s ON s.id = st.series_id WHERE s.provider_id = {q(prov)};
  SELECT count(*) INTO e FROM alu_kg_prices WHERE provider_id = {q(prov)};
  SELECT count(*) INTO f FROM alu_profiles WHERE provider_id = {q(prov)} AND image_path IS NOT NULL;
  IF a <> {len(SER)} OR b <> {len(profiles)} OR c <> {len(links)} OR d <> {nt} OR e <> {len(FIN)} OR f <> {len(imgs)} THEN
    RAISE EXCEPTION 'count mismatch: series % profiles % links % types % prices % images %', a, b, c, d, e, f; END IF;
END $$;""")
L.append(f"SELECT f.name family, s.name series, count(sp.id) profiles FROM alu_series s JOIN alu_series_families f ON f.id = s.series_family_id LEFT JOIN alu_series_profiles sp ON sp.series_id = s.id WHERE s.provider_id = {q(prov)} GROUP BY f.name, f.sort_order, s.name ORDER BY f.sort_order, s.name;")
L.append("COMMIT;")
open(ROOT+'/supabase/datafix/2026-11-04-import-aluwork.sql','w').write('\n'.join(L)+'\n')
print('profiles',len(profiles),'links',len(links),'imgs',len(imgs),'inactive',[p['key'] for p in profiles if not p['active']],'std walls',FAM[1][2])
print('basis',{b.split()[0] for b in (p['basis'] for p in profiles)})
for p in profiles[:3]: print(p['code'],p.get('wall_mm'),round(p['kgm'],4),p['basis'])
