# Generates the Muangthong EURO 2024 import (supabase/datafix/2026-11-04-import-muangthong-euro.sql) into the existing MT extruder.
import json, uuid, os
from PIL import Image, ImageDraw, ImageFont
ROOT='/Users/plfx/code/FacadeXPM/facadex-app'
X=ROOT+'/DOC/ALUMNIUM CATALOG/_extracted/muangthong-euro-sections'
OUT=os.path.dirname(os.path.abspath(__file__))
T='1b9affc4-2136-4ed1-b168-a36e6624e743'
d=json.load(open(ROOT+'/docs/catalogs/muangthong/muangthong-euro-2024.json'))
man={m['die']:m for m in json.load(open(X+'/manifest.json')) if m.get('file')}
prov=str(uuid.uuid5(uuid.UUID('6f1c2a90-0000-4000-8000-0000004d5401'),'provider'))   # MT, from 2026-11-04-import-muangthong.gen.py
ns=uuid.UUID('6f1c2a90-0000-4000-8000-0000004d5402')
uid=lambda *k: str(uuid.uuid5(ns,'|'.join(map(str,k))))
S=['ยูโร บานเลื่อน / ประตูบานเลื่อน (GROUP 1)','ยูโร บานกระทุ้ง / บานเปิด ร่อง Groove (GROUP 2)','ยูโร บานกระทุ้ง / บานเปิด ไม่มีร่อง (GROUP 3)','ยูโร ประตูบานเฟี้ยม / บานเปิด (GROUP 4)']
SHARED_BEADS={'30055','30056','30265','30357','50611','50612','50726'}   # listed in GROUP 2, used by 3 and 4 too
FAM='เมืองทอง ยูโร'
q=lambda s: "'"+str(s).replace("'","''")+"'" if s is not None else 'NULL'
num=lambda v: 'NULL' if v in (None,'') else repr(float(v))
fmt=lambda v: ('%g' % float(v)) if v not in (None,'') else None
profiles={}; links=[]
for i,s in enumerate(d['series']):
    sid=uid('series',S[i])
    for p in s['profiles']:
        die=p['die_no'].strip()
        profiles.setdefault(die, dict(p, id=uid('profile',die), die=die))
        links.append((sid, profiles[die]['id'], p.get('role_family') or 'อื่นๆ'))
        if die in SHARED_BEADS:
            for j in (2,3): links.append((uid('series',S[j]), profiles[die]['id'], p.get('role_family') or 'อื่นๆ'))
links=list(dict.fromkeys(links))
font=ImageFont.truetype('/System/Library/Fonts/Helvetica.ttc',30)
os.makedirs(OUT+'/img',exist_ok=True); imgs=[]
def label(t):
    if t in (None,''): return 't = ?'
    v=float(t); return 't = '+(f'{v:.1f}' if round(v,1)==v else f'{v:g}')+' mm'
for p in profiles.values():
    m=man.get(p['die'])
    if not m: p['image_path']=None; continue
    im=Image.open(X+'/'+m['file']).convert('RGB'); w,h=im.size; band=48
    o=Image.new('RGB',(w,h+band),'white'); o.paste(im,(0,0)); dr=ImageDraw.Draw(o); lb=label(p.get('wall_mm'))
    dr.text(((w-dr.textlength(lb,font=font))/2,h+6),lb,fill='black',font=font)
    fn=p['id']+'.png'; o.save(OUT+'/img/'+fn,optimize=True)
    p['image_path']=f'{T}/profiles/{p["id"]}.png'; imgs.append({'id':p['id'],'file':fn,'code':p['die']})
json.dump(imgs,open(OUT+'/list.json','w'))
L=["-- Owner 2026-11-04: \"เมืองทองก่อน ราคาเหมือน sms\" — Muangthong EURO 2024 (แคตตาล็อคยูโรเมืองทอง2024.pdf) into the MT extruder",
"-- as family 'เมืองทอง ยูโร'. Weights/walls: docs/catalogs/muangthong/muangthong-euro-2024.json (read from the page images).",
"-- Colours and kg prices are the MT extruder's (SMS rates). Generated by 2026-11-04-import-muangthong-euro.gen.py; refuses to run twice.",
"BEGIN;",
f"DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM alu_providers WHERE id = {q(prov)}) THEN RAISE EXCEPTION 'MT extruder missing'; END IF;",
f"  IF EXISTS (SELECT 1 FROM alu_series_families WHERE id = {q(uid('family'))}) THEN RAISE EXCEPTION 'Euro already imported'; END IF; END $$;",
f"INSERT INTO alu_series_families (id, tenant_id, provider_id, name, sort_order, active) VALUES ({q(uid('family'))}, {q(T)}, {q(prov)}, {q(FAM)}, 6, true);"]
for i,s in enumerate(d['series']):
    sid=uid('series',S[i])
    L.append(f"INSERT INTO alu_series (id, tenant_id, provider_id, name, is_base, active, series_family_id) VALUES ({q(sid)}, {q(T)}, {q(prov)}, {q(S[i])}, false, true, {q(uid('family'))});")
    for t in s['app_types']:
        L.append(f"INSERT INTO alu_series_types (tenant_id, series_id, type_id) SELECT {q(T)}, {q(sid)}, id FROM door_window_types WHERE tenant_id = {q(T)} AND name = {q(t)};")
for p in profiles.values():
    L.append("INSERT INTO alu_profiles (id, tenant_id, provider_id, name, drawing_no, family, thickness_mm, linear_weight_kg_per_m, default_length_m, width_mm, depth_mm, active, image_path) VALUES "
             f"({q(p['id'])}, {q(T)}, {q(prov)}, {q(p['name'])}, {q(p['die'])}, {q(p.get('role_family') or 'อื่นๆ')}, {num(p.get('wall_mm'))}, {num(p['kg_per_m'])}, {num(p.get('std_length_m') or 6.4)}, {num(p.get('width_mm'))}, {num(p.get('depth_mm'))}, true, {q(p['image_path'])});")
for sid,pid,fam in links:
    L.append(f"INSERT INTO alu_series_profiles (tenant_id, series_id, profile_id, family) VALUES ({q(T)}, {q(sid)}, {q(pid)}, {q(fam)});")
nt=sum(len(s['app_types']) for s in d['series'])
L.append(f"""DO $$ DECLARE a int; b int; c int; d int; f int; BEGIN
  SELECT count(*) INTO a FROM alu_series WHERE series_family_id = {q(uid('family'))};
  SELECT count(*) INTO b FROM alu_profiles WHERE id IN ({', '.join(q(p['id']) for p in profiles.values())});
  SELECT count(*) INTO c FROM alu_series_profiles sp JOIN alu_series s ON s.id = sp.series_id WHERE s.series_family_id = {q(uid('family'))};
  SELECT count(*) INTO d FROM alu_series_types st JOIN alu_series s ON s.id = st.series_id WHERE s.series_family_id = {q(uid('family'))};
  SELECT count(*) INTO f FROM alu_profiles WHERE id IN ({', '.join(q(p['id']) for p in profiles.values())}) AND image_path IS NOT NULL;
  IF a <> {len(S)} OR b <> {len(profiles)} OR c <> {len(links)} OR d <> {nt} OR f <> {len(imgs)} THEN
    RAISE EXCEPTION 'count mismatch: series % profiles % links % types % images %', a, b, c, d, f; END IF;
END $$;""")
L.append(f"SELECT s.name series, (SELECT count(*) FROM alu_series_profiles sp WHERE sp.series_id = s.id) profiles, (SELECT string_agg(t.name, ' | ') FROM alu_series_types st JOIN door_window_types t ON t.id = st.type_id WHERE st.series_id = s.id) types FROM alu_series s WHERE s.series_family_id = {q(uid('family'))} ORDER BY s.name;")
L.append("COMMIT;")
open(ROOT+'/supabase/datafix/2026-11-04-import-muangthong-euro.sql','w').write('\n'.join(L)+'\n')
print('profiles',len(profiles),'links',len(links),'types',nt,'imgs',len(imgs))
