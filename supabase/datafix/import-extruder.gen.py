# Generic extruder import from one or more extraction parts (docs/catalogs/<brand>/*.json + _extracted/<x>-sections).
# Usage: python3 gen.py <config.json>. Config: {slug, owner_note, provider_name, short_name, finishes:[[name,price]...],
#   parts:[{json, sections}], families:{family:[sort, thickness_options|null]}, series_family:{series name: family},
#   series_rename:{orig: new}, zero_weight_ok: bool, inactive_dies:[...]}
# Weight: the part's kg_per_m (extraction rule: powder-coat midpoint / bar length). No weight -> 0 only if zero_weight_ok
# (the catalogue page shows the red "ไม่มีน้ำหนัก" badge), otherwise the row is skipped and listed.
import json, uuid, os, re, sys
from PIL import Image, ImageDraw, ImageFont
ROOT='/Users/plfx/code/FacadeXPM/facadex-app'; T='1b9affc4-2136-4ed1-b168-a36e6624e743'
C=json.load(open(sys.argv[1])); OUT=os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), C['slug'])
ns=uuid.uuid5(uuid.UUID('6f1c2a90-0000-4000-8000-00000000e170'), C['slug'])
uid=lambda *k: str(uuid.uuid5(ns,'|'.join(map(str,k))))
q=lambda s: "'"+str(s).replace("'","''")+"'" if s is not None else 'NULL'
num=lambda v: 'NULL' if v in (None,'') else repr(round(float(v),4))
prov=uid('provider'); series=[]; profiles={}; links=[]; skipped=[]
for part in C['parts']:
    d=json.load(open(ROOT+'/'+part['json']))
    X=ROOT+'/'+part['sections']; man={m['die']:m for m in json.load(open(X+'/manifest.json')) if m.get('file')}
    for s in d['series']:
        sname=C.get('series_rename',{}).get(s['name'],s['name']); fam=C['series_family'].get(s['name']) or C['series_family'].get(sname)
        if fam is None: raise SystemExit('no family for series: '+s['name'])
        sid=uid('series',sname)
        if sid not in [x[0] for x in series]: series.append((sid,sname,fam,s.get('app_types') or []))
        for p in s['profiles']:
            die=p['die_no'].strip(); key=(die, p.get('wall_mm'))
            kg=C.get('kg_override',{}).get(die, p.get('kg_per_m'))
            if not kg:
                if not C.get('zero_weight_ok'): skipped.append(die); continue
                kg=0
            if key not in profiles:
                m=man.get(die)
                profiles[key]=dict(p, die=die, id=uid('profile',*key), kg=kg, pic=(X+'/'+m['file']) if m else None,
                                   active=die not in C.get('inactive_dies',[]))
            links.append((sid, profiles[key]['id'], p.get('role_family') or 'อื่นๆ'))
links=list(dict.fromkeys(links)); P=list(profiles.values())
font=ImageFont.truetype('/System/Library/Fonts/Helvetica.ttc',30)
os.makedirs(OUT+'/img',exist_ok=True); imgs=[]
def label(t):
    if t in (None,''): return 't = ?'
    v=float(t); return 't = '+(f'{v:.1f}' if round(v,1)==v else f'{v:g}')+' mm'
for p in P:
    if not p['pic']: p['image_path']=None; continue
    im=Image.open(p['pic']).convert('RGB'); w,h=im.size; band=48
    o=Image.new('RGB',(w,h+band),'white'); o.paste(im,(0,0)); dr=ImageDraw.Draw(o); lb=label(p.get('wall_mm'))
    dr.text(((w-dr.textlength(lb,font=font))/2,h+6),lb,fill='black',font=font)
    fn=p['id']+'.png'; o.save(OUT+'/img/'+fn,optimize=True)
    p['image_path']=f'{T}/profiles/{p["id"]}.png'; imgs.append({'id':p['id'],'file':fn,'code':p['die']})
json.dump(imgs,open(OUT+'/list.json','w'))
L=[f"-- {C['owner_note']}",f"-- Parts: {', '.join(x['json'] for x in C['parts'])}. Generated by {C['slug']}.gen.py + .config.json; refuses to run twice.",
   "BEGIN;",
   f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM alu_providers WHERE tenant_id = {q(T)} AND (id = {q(prov)} OR short_name = {q(C['short_name'])})) THEN RAISE EXCEPTION 'already imported'; END IF; END $$;",
   f"INSERT INTO alu_providers (id, tenant_id, name, short_name, price_basis, active) VALUES ({q(prov)}, {q(T)}, {q(C['provider_name'])}, {q(C['short_name'])}, 'per_kg', true);"]
for name,price in C['finishes']:
    fid=uid('finish',name)
    L.append(f"INSERT INTO alu_finishes (id, tenant_id, provider_id, name, active) VALUES ({q(fid)}, {q(T)}, {q(prov)}, {q(name)}, true);")
    L.append(f"INSERT INTO alu_kg_prices (tenant_id, provider_id, finish_id, price_per_kg, effective_from, source) VALUES ({q(T)}, {q(prov)}, {q(fid)}, {price}, '2026-01-01', 'same as SMS shop rate (owner 2026-11-04)');")
for f,(o,th) in C['families'].items():
    L.append(f"INSERT INTO alu_series_families (id, tenant_id, provider_id, name, thickness_options, sort_order, active) VALUES ({q(uid('family',f))}, {q(T)}, {q(prov)}, {q(f)}, {q(th) if th else 'NULL'}, {o}, true);")
for sid,sname,fam,types in series:
    L.append(f"INSERT INTO alu_series (id, tenant_id, provider_id, name, is_base, active, series_family_id) VALUES ({q(sid)}, {q(T)}, {q(prov)}, {q(sname)}, false, true, {q(uid('family',fam))});")
    for t in types:
        L.append(f"INSERT INTO alu_series_types (tenant_id, series_id, type_id) SELECT {q(T)}, {q(sid)}, id FROM door_window_types WHERE tenant_id = {q(T)} AND name = {q(t)};")
for p in P:
    L.append("INSERT INTO alu_profiles (id, tenant_id, provider_id, name, drawing_no, family, thickness_mm, linear_weight_kg_per_m, default_length_m, width_mm, depth_mm, active, image_path) VALUES "
             f"({q(p['id'])}, {q(T)}, {q(prov)}, {q(p['name'])}, {q(p['die'])}, {q(p.get('role_family') or 'อื่นๆ')}, {num(p.get('wall_mm'))}, {num(p['kg'])}, {num(p.get('std_length_m') or 6.4)}, {num(p.get('width_mm'))}, {num(p.get('depth_mm'))}, {'true' if p['active'] else 'false'}, {q(p['image_path'])});")
for sid,pid,fam in links:
    L.append(f"INSERT INTO alu_series_profiles (tenant_id, series_id, profile_id, family) VALUES ({q(T)}, {q(sid)}, {q(pid)}, {q(fam)});")
nt=sum(len(s[3]) for s in series)
L.append(f"""DO $$ DECLARE a int; b int; c int; f int; e int; BEGIN
  SELECT count(*) INTO a FROM alu_series WHERE provider_id = {q(prov)};
  SELECT count(*) INTO b FROM alu_profiles WHERE provider_id = {q(prov)};
  SELECT count(*) INTO c FROM alu_series_profiles sp JOIN alu_series s ON s.id = sp.series_id WHERE s.provider_id = {q(prov)};
  SELECT count(*) INTO f FROM alu_profiles WHERE provider_id = {q(prov)} AND image_path IS NOT NULL;
  SELECT count(*) INTO e FROM alu_kg_prices WHERE provider_id = {q(prov)};
  IF a <> {len(series)} OR b <> {len(P)} OR c <> {len(links)} OR f <> {len(imgs)} OR e <> {len(C['finishes'])} THEN
    RAISE EXCEPTION 'count mismatch: series % profiles % links % images % prices %', a, b, c, f, e; END IF;
END $$;""")
L.append(f"SELECT f.name family, s.name series, count(sp.id) profiles, (SELECT count(*) FROM alu_series_types st WHERE st.series_id = s.id) types FROM alu_series s JOIN alu_series_families f ON f.id = s.series_family_id LEFT JOIN alu_series_profiles sp ON sp.series_id = s.id WHERE s.provider_id = {q(prov)} GROUP BY f.name, f.sort_order, s.id, s.name ORDER BY f.sort_order, s.name;")
L.append("COMMIT;")
open(f"{ROOT}/supabase/datafix/{C['slug']}.sql",'w').write('\n'.join(L)+'\n')
print('series',len(series),'profiles',len(P),'links',len(links),'imgs',len(imgs),'zero kg',sum(1 for p in P if not p['kg']),'skipped',skipped,'types',nt)
